"""## 5. Extract text and split it into chunks"""

import io
import ipywidgets as widgets

# Ensure uploader variable is defined
if 'uploader' not in globals():
    uploader = None

# Redefine get_uploaded_pdf to guarantee the safety check runs
def get_uploaded_pdf(upload_widget):
    if upload_widget is None:
        raise ValueError("Upload widget has not been initialized. Please run the 'Upload a PDF' cell above.")
    value = upload_widget.value
    if not value:
        raise ValueError("Please choose a PDF first by clicking 'Choose PDF' in the cell above.")

    if isinstance(value, dict):
        file_info = next(iter(value.values()))
        filename = next(iter(value.keys()))
        content = file_info["content"]
    else:
        file_info = value[0]
        filename = file_info.get("name", "uploaded.pdf")
        content = file_info["content"]

    if not filename.lower().endswith(".pdf"):
        raise ValueError("Please upload a .pdf file.")
    return filename, bytes(content)

try:
    filename, pdf_bytes = get_uploaded_pdf(uploader)
    reader = PdfReader(io.BytesIO(pdf_bytes))

    pages = []
    for page_number, page in enumerate(reader.pages, start=1):
        text = page.extract_text() or ""
        if text.strip():
            pages.append((page_number, text))

    if not pages:
        raise ValueError("No selectable text found. This may be a scanned PDF; OCR is needed for scanned pages.")

    def split_text(text, chunk_size=1000, overlap=150):
        text = " ".join(text.split())
        chunks = []
        start = 0
        while start < len(text):
            end = min(start + chunk_size, len(text))
            chunk = text[start:end].strip()
            if chunk:
                chunks.append(chunk)
            if end == len(text):
                break
            start = end - overlap
        return chunks

    documents = []
    metadatas = []
    for page_number, page_text in pages:
        for chunk_number, chunk in enumerate(split_text(page_text), start=1):
            documents.append(chunk)
            metadatas.append({
                "source": filename,
                "page": page_number,
                "chunk": chunk_number
            })

    print(f"PDF: {filename}")
    print(f"Pages with text: {len(pages)}")
    print(f"Text chunks created: {len(documents)}")
    print("\nSample chunk:\n", documents[0][:500])
except (NameError, ValueError) as e:
    print("Status:", e)
    print("Please make sure you have run the preceding 'Upload a PDF' cell and uploaded a PDF file.")

"""## 6. Create embeddings and save them in ChromaDB

This calls Ollama's local embedding API. If the model is missing, run `ollama pull nomic-embed-text` in your terminal.

"""

if 'documents' not in globals() or not documents:
    print("Status: No document chunks available. Please upload and parse a PDF first before indexing.")
else:
    def ollama_embedding(text):
        response = requests.post(
            f"{OLLAMA_URL}/api/embeddings",
            json={"model": EMBED_MODEL, "prompt": text},
            timeout=120
        )
        response.raise_for_status()
        return response.json()["embedding"]

    # Create a local persistent vector database folder.
    client = chromadb.PersistentClient(path="./chroma_db")

    # Use a fresh collection for this notebook run.
    collection_name = "pdf_rag_collection"
    try:
        client.delete_collection(collection_name)
    except Exception:
        pass

    collection = client.create_collection(
        name=collection_name,
        metadata={"hnsw:space": "cosine"}
    )

    batch_size = 16
    for start in range(0, len(documents), batch_size):
        batch_docs = documents[start:start + batch_size]
        batch_meta = metadatas[start:start + batch_size]
        batch_ids = [f"chunk_{i}" for i in range(start, start + len(batch_docs))]
        batch_embeddings = [ollama_embedding(doc) for doc in batch_docs]

        collection.add(
            ids=batch_ids,
            documents=batch_docs,
            metadatas=batch_meta,
            embeddings=batch_embeddings
        )
        print(f"Indexed {min(start + len(batch_docs), len(documents))}/{len(documents)} chunks")

    print("Finished! Your PDF is indexed in ChromaDB.")

"""## 7. Retrieve relevant chunks and ask Ollama"""

def retrieve_context(question, top_k=4):
    query_embedding = ollama_embedding(question)
    results = collection.query(
        query_embeddings=[query_embedding],
        n_results=min(top_k, collection.count()),
        include=["documents", "metadatas", "distances"]
    )

    retrieved_docs = results.get("documents", [[]])[0]
    retrieved_meta = results.get("metadatas", [[]])[0]
    context_parts = []

    for doc, meta in zip(retrieved_docs, retrieved_meta):
        context_parts.append(
            f"[Source: {meta.get('source', 'PDF')}, page {meta.get('page', '?')}]\n{doc}"
        )
    return "\n\n".join(context_parts)

def ask_pdf(question):
    if not question.strip():
        print("Enter a question.")
        return

    context = retrieve_context(question)
    prompt = f"""You are an assistant answering questions about an uploaded PDF.
Use only the context below to answer. If the answer is not present in the context,
say: "I couldn't find that information in the uploaded PDF."
Do not invent facts. Mention page numbers when useful.

CONTEXT:
{context}

QUESTION:
{question}

ANSWER:"""

    response = requests.post(
        f"{OLLAMA_URL}/api/generate",
        json={
            "model": CHAT_MODEL,
            "prompt": prompt,
            "stream": False
        },
        timeout=180
    )
    response.raise_for_status()
    answer = response.json().get("response", "")
    print(answer)
    print("\n--- Retrieved context ---")
    print(context[:2500])

print("Ready! Try: ask_pdf('What is the main topic of this document?')")

"""## 8. Chat with your PDF"""

question_box = widgets.Text(
    placeholder="Ask a question about your PDF...",
    description="Question:",
    layout=widgets.Layout(width="85%")
)
ask_button = widgets.Button(description="Ask PDF", button_style="primary")
output = widgets.Output()

def on_ask_clicked(_):
    with output:
        output.clear_output()
        try:
            ask_pdf(question_box.value)
        except Exception as error:
            print("Something went wrong:", error)
            print("Check that Ollama is running and both models are installed.")

ask_button.on_click(on_ask_clicked)
display(widgets.VBox([question_box, ask_button, output]))

